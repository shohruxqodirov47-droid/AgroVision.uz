class I18nEngine {
  constructor() {
    this.currentLang = window.appStore ? window.appStore.get('lang') || 'uz' : 'uz';
  }

  setLang(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      if (window.appStore) window.appStore.set('lang', lang);
      this.updateDOM();
    }
  }

  t(key) {
    const dict = translations[this.currentLang] || translations.uz;
    return dict[key] || translations.uz[key] || key;
  }

  updateDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) el.placeholder = text;
      } else {
        el.innerText = text;
      }
    });
  }
}

window.i18n = new I18nEngine();
